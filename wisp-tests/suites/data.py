from ._common import *

@step('Bookmark a page, find it in Bookmarks, open it')
def _():
    goto('/title?t=Bookmark%20me', expect='Bookmark me')
    menu('Bookmark', wait=1)
    shot('after bookmark')
    menu('Bookmarks', wait=2.5)
    shot('bookmarks')
    n = wait_for(timeout=4, text='Bookmark me')
    check(n, 'bookmark not in the list')
    tap_xy(*n.center)
    sleep(3)
    if not wisp_in_front():
        launch(2)
    expect('/title' in (address() or ''), 'bookmark did not open the page: %r' % address())

@step('Bookmarks survive Quit')
def _():
    quit_wisp()
    launch()
    menu('Bookmarks', wait=2.5)
    expect(present(text='Bookmark me'), 'bookmark gone after Quit')
    to_base()

@step('History screen opens a page')
def _():
    goto('/title?t=From%20history', expect='From history')
    goto('/other.html', expect='Other page')
    menu('History', wait=2.5)
    n = wait_for(timeout=4, text='From history')
    check(n, 'page not in History')
    tap_xy(*n.center)
    sleep(3)
    if not wisp_in_front():
        launch(2)
    expect(page_has('From history', 5), 'History did not open the page')

@step('Backup: short and mismatched passwords are refused')
def _():
    open_settings('Security')
    n = scroll_to(4, text='Back up to a file')
    check(n, 'no backup row')
    tap_xy(*n.center)
    sleep(1.5)
    shot('backup dialog')
    tap(text='Password for the backup')
    type_text('abc')
    tap(text='The same password again')
    type_text('abc')
    press_button('OK')
    sleep(1)
    expect(present(text='Password for the backup') or present(text='At least 6'), 'short password accepted')
    shot('short password')
    press_button('Cancel', timeout=2)
    leave_settings()

@step('Backup to a file')
def _():
    sh('rm -f /sdcard/Download/Wisp-backup-*')
    open_settings('Security')
    tap(text='Back up to a file')
    sleep(1.5)
    tap(text='Password for the backup')
    type_text('test-pass-123')
    tap(text='The same password again')
    type_text('test-pass-123')
    press_button('OK')
    sleep(2)
    picker_save()
    for _ in range(10):
        if wisp_in_front():
            break
        sleep(1)
    sleep(3)
    shot('after backup')
    f = sh('ls -l /sdcard/Download/ | grep -i wisp-backup').strip()
    note('backup file: %s' % f)
    check(f, 'no backup file in Download')
    leave_settings()

@step('Restore: wrong password is refused')
def _():
    open_settings('Security')
    tap(text='Restore from a file')
    picker_pick('Wisp-backup')
    sleep(2)
    tap(text='Backup password')
    type_text('wrong-pass')
    press_button('OK')
    sleep(3)
    shot('wrong password')
    t = ' '.join(texts())
    note('texts: %s' % [x for x in texts() if 'password' in x.lower()][:3])
    expect('Wrong password' in t or present(text='Backup password'), 'no wrong-password message')
    press_button('Cancel', 'OK', timeout=2)
    leave_settings()

@step('Restore from the backup, Wisp restarts')
def _():
    open_settings('Security')
    tap(text='Restore from a file')
    picker_pick('Wisp-backup')
    sleep(2)
    tap(text='Backup password')
    type_text('test-pass-123')
    press_button('OK')
    sleep(5)
    shot('restored')
    t = ' '.join(texts())
    note('restore message: %s' % [x for x in texts() if 'added' in x or 'restored' in x.lower()][:3])
    check('Restored' in t or 'added' in t, 'no "Restored" message')
    press_button('Restart Wisp', 'OK', timeout=4)
    sleep(6)
    if not wisp_in_front():
        launch()
    check(wisp_running(), 'Wisp did not come back after restore')
    menu('Bookmarks', wait=2.5)
    expect(present(text='Bookmark me'), 'bookmark missing after restore')
    to_base()
