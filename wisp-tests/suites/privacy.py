@step('Quit removes history, tabs and cookies')
def _():
    goto('/setcookie?name=gone&value=1', expect='COOKIE SET', site=SITE2)
    goto('/title?t=Before%20quit', expect='Before quit')
    quit_wisp()
    check(not wisp_in_front(), 'Wisp still open after Quit')
    launch()
    note('after restart: counter %r, address %r' % (tab_count(), address()))
    expect(tab_count() == 0, 'tabs kept after Quit')
    goto('/cookies', site=SITE2)
    sleep(1)
    expect(page_has('COOKIES: none', 4), 'cookie kept after Quit: %s' % [t for t in texts() if 'COOKIES' in t])
    menu('History', wait=2.5)
    expect(not present(text='Before quit'), 'history kept after Quit')
    shot('history after quit')
    back()
    if not wisp_in_front():
        launch(2)

@step('Stay logged in keeps the login through Quit')
def _():
    login('alice')
    check(account_user() == 'alice', 'login did not work: %r' % account_user())
    login('bob', site=SITE2)
    site_sheet()
    note('site sheet: %s' % texts()[:10])
    goto('/account')
    site_sheet()
    set_switch('Stay logged in', True)
    back()
    goto('/app/', expect='APP FOLDER')
    goto('/setcookie?name=sub&value=1', expect='COOKIE SET', site='http://app.lvh.me:%d' % PORT)
