from ._common import *

def account_user(site=SITE):
    goto('/account', site=site)
    sleep(1)
    t = ' '.join(texts())
    if 'Logged in as' in t:
        rest = t.split('Logged in as', 1)[1].split()
        return rest[0] if rest else ''
    return '' if 'Not logged in' in t else None

def login(user, site=SITE):
    goto('/login', expect='Sign in', site=site)
    tap(text='Username')
    type_text(user)
    tap(text='Password')
    type_text('pw-' + user)
    end_typing()
    btns = find(text='Sign in', exact=True)
    check(btns, 'no Sign in button')
    tap_xy(*btns[-1].center)
    sleep(3)
    press_button('Not now', timeout=3)

