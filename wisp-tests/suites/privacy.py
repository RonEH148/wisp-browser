    check(n, 'no WebRTC switch')
    set_switch('Block WebRTC IP leak', False)
    leave_settings()
    goto('/webrtc.html', expect='WebRTC test')
    sleep(8)
    off = [t for t in texts() if t.startswith('WEBRTC:')]
    note('switch off: %s' % off)
    open_settings('Privacy and security')
    scroll_to(6, text='Block WebRTC IP leak')
    set_switch('Block WebRTC IP leak', True)
    leave_settings()
    goto('/webrtc.html', expect='WebRTC test')
    sleep(8)
    on = [t for t in texts() if t.startswith('WEBRTC:')]
    note('switch on: %s' % on)
    expect(on and 'host' not in on[0], 'host candidates with the switch on: %s' % on)

